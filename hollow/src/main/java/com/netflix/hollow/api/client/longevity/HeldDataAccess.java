package com.netflix.hollow.api.client.longevity;

import com.netflix.hollow.api.consumer.longevity.HollowVersionHold;
import com.netflix.hollow.core.read.dataaccess.HollowListTypeDataAccess;
import com.netflix.hollow.core.read.dataaccess.HollowMapTypeDataAccess;
import com.netflix.hollow.core.read.dataaccess.HollowObjectTypeDataAccess;
import com.netflix.hollow.core.read.dataaccess.HollowSetTypeDataAccess;
import com.netflix.hollow.core.read.dataaccess.HollowTypeDataAccess;
import com.netflix.hollow.core.read.dataaccess.proxy.HollowListProxyDataAccess;
import com.netflix.hollow.core.read.dataaccess.proxy.HollowMapProxyDataAccess;
import com.netflix.hollow.core.read.dataaccess.proxy.HollowObjectProxyDataAccess;
import com.netflix.hollow.core.read.dataaccess.proxy.HollowProxyDataAccess;
import com.netflix.hollow.core.read.dataaccess.proxy.HollowSetProxyDataAccess;
import com.netflix.hollow.core.read.dataaccess.proxy.HollowTypeProxyDataAccess;
import com.netflix.hollow.core.read.engine.HollowTypeReadState;
import java.util.BitSet;

/**
 * A hold's data access. Its types answer their populated ordinals and max ordinal for the hold's version, so indexes and
 * {@code getAll…} built over it see that version, and never return a type state, which follows the state engine.
 */
final class HeldDataAccess extends HollowProxyDataAccess {
    private final HollowVersionHold hold;

    HeldDataAccess(HollowVersionHold hold) {
        this.hold = hold;
    }

    @Override
    protected HollowTypeProxyDataAccess newTypeProxy(HollowTypeDataAccess typeDataAccess) {
        if (typeDataAccess instanceof HollowObjectTypeDataAccess) {
            return new HollowObjectProxyDataAccess(this) {
                @Override public BitSet getPopulatedOrdinals() { return populated(this); }
                @Override public int getMaxOrdinal() { return populated(this).length() - 1; }
                @Override public HollowTypeReadState getTypeState() { throw noTypeState(this); }
            };
        } else if (typeDataAccess instanceof HollowListTypeDataAccess) {
            return new HollowListProxyDataAccess(this) {
                @Override public BitSet getPopulatedOrdinals() { return populated(this); }
                @Override public int getMaxOrdinal() { return populated(this).length() - 1; }
                @Override public HollowTypeReadState getTypeState() { throw noTypeState(this); }
            };
        } else if (typeDataAccess instanceof HollowSetTypeDataAccess) {
            return new HollowSetProxyDataAccess(this) {
                @Override public BitSet getPopulatedOrdinals() { return populated(this); }
                @Override public int getMaxOrdinal() { return populated(this).length() - 1; }
                @Override public HollowTypeReadState getTypeState() { throw noTypeState(this); }
            };
        } else if (typeDataAccess instanceof HollowMapTypeDataAccess) {
            return new HollowMapProxyDataAccess(this) {
                @Override public BitSet getPopulatedOrdinals() { return populated(this); }
                @Override public int getMaxOrdinal() { return populated(this).length() - 1; }
                @Override public HollowTypeReadState getTypeState() { throw noTypeState(this); }
            };
        }
        return super.newTypeProxy(typeDataAccess);
    }

    private BitSet populated(HollowTypeDataAccess type) {
        return hold.getPopulatedOrdinals(type.getSchema().getName());
    }

    private UnsupportedOperationException noTypeState(HollowTypeDataAccess type) {
        return new UnsupportedOperationException("A hold of version " + hold.getVersion() + " has no type state for "
                + type.getSchema().getName() + ": a type state follows the state engine. Use getPopulatedOrdinals() "
                + "and getMaxOrdinal(), and an API generated by this version of Hollow or later for getAll…");
    }
}
